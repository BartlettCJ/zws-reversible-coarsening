"""Export a selected rule as a self-contained exact-integer oracle for Eshkol.

Eshkol (https://github.com/tsotchke/eshkol) is a Scheme-based language compiled to
native code via LLVM, written by tsotchke and released under the MIT licence.  This
project pins release v1.3.4-evolve and uses it unmodified as an independent compiler
and runtime; see eshkol/README.md for the citation its authors ask for.
"""

from __future__ import annotations

from pathlib import Path

from .rules import ReversibleRule


def export_eshkol_oracle(rule: ReversibleRule, path: str | Path) -> Path:
    """Emit a self-contained exact local-rule verifier for Eshkol/R7RS Scheme."""
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    table = " ".join(str(int(value)) for value in rule.table.tolist())
    program = f'''\
;; Generated by ZWSLab. Exact integer local-rule oracle.
;; Rule: {rule.name}
;; Run with: eshkol-run {destination.name}

(define rule '#({table}))
(define seen (make-vector 256 #f))
(define failures 0)

(define (digit code place)
  (modulo (quotient code place) 4))

(define (state-charge state)
  (cond ((= state 1) 1)
        ((= state 2) -1)
        (else 0)))

(define (block-charge code)
  (+ (state-charge (digit code 1))
     (state-charge (digit code 4))
     (state-charge (digit code 16))
     (state-charge (digit code 64))))

(define (check i)
  (if (= i 256)
      #t
      (let ((out (vector-ref rule i)))
        (if (or (< out 0) (>= out 256))
            (begin (display "OUT-OF-RANGE ") (display i) (newline)
                   (set! failures (+ failures 1)))
            (begin
              (if (vector-ref seen out)
                  (begin (display "DUPLICATE-OUTPUT ") (display out) (newline)
                         (set! failures (+ failures 1)))
                  (vector-set! seen out #t))
              (if (not (= (block-charge i) (block-charge out)))
                  (begin (display "CHARGE-FAIL ") (display i)
                         (display " -> ") (display out) (newline)
                         (set! failures (+ failures 1))))))
        (check (+ i 1)))))

(check 0)
(display "RULE {rule.name}: ")
(if (= failures 0)
    (display "PASS -- bijective and exactly charge-preserving on all 256 blocks")
    (begin (display "FAILURES=") (display failures)))
(newline)
'''
    destination.write_text(program, encoding="utf-8")
    return destination
