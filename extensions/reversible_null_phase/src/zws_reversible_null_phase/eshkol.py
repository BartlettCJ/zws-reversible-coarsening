"""Eshkol parity oracle: exhaustive rule audit and cell-for-cell replay in an
independent compiler and runtime.

Eshkol (https://github.com/tsotchke/eshkol) is a Scheme-based language compiled to
native code via LLVM, written by tsotchke and released under the MIT licence.  This
project pins release v1.3.4-evolve and uses it unmodified; see docs/ESHKOL_PARITY.md
and the root eshkol/README.md for the citation its authors ask for.
"""

from __future__ import annotations

import json
from pathlib import Path
import subprocess
from typing import Any

import torch

from .atomic import atomic_write_json, atomic_write_text
from .initial import inventory_for_density, make_state, state_sha256
from .rule import ReversibleRule
from .simulator import step_rule


def _vector_literal(values: list[int]) -> str:
    # Eshkol's #(...) syntax creates a tensor-backed vector.  Numeric values
    # read from that representation are inexact scalars and cannot safely be
    # reused as indices into ordinary vectors.  The R7RS (vector ...) form
    # preserves the exact integers required by this parity oracle.
    return "(vector " + " ".join(str(int(value)) for value in values) + ")"


def generate_eshkol_parity_source(
    rule: ReversibleRule,
    initial: torch.Tensor,
    *,
    steps: int,
) -> str:
    """Generate a self-contained exact Eshkol simulator and local audit.

    The program prints the complete final lattice.  Python compares every cell,
    so no agreement can hide behind a weak checksum.
    """
    if initial.ndim != 2:
        raise ValueError("initial state must be [H,W]")
    height, width = initial.shape
    if height % 2 or width % 2:
        raise ValueError("Margolus dimensions must be even")
    table = [int(x) for x in rule.table.tolist()]
    values = [int(x) for x in initial.reshape(-1).tolist()]
    charges = [0, 1, -1, 0]
    occupancy = [0, 1, 1, 1]
    return f''';; Generated by ZWS Reversible Null Phase Study v0.3.0
;; Independent exact-integer parity replay for rule {rule.sha256()}

(define width {width})
(define height {height})
(define steps {steps})
(define rule {_vector_literal(table)})
(define charges {_vector_literal(charges)})
(define occupancy {_vector_literal(occupancy)})
(define initial {_vector_literal(values)})

(define (cell-a code) (modulo code 4))
(define (cell-b code) (modulo (quotient code 4) 4))
(define (cell-c code) (modulo (quotient code 16) 4))
(define (cell-d code) (modulo (quotient code 64) 4))
(define (encode a b c d) (+ a (* 4 b) (* 16 c) (* 64 d)))
(define (index y x) (+ (* (modulo y height) width) (modulo x width)))
(define (charge-code code)
  (+ (vector-ref charges (cell-a code))
     (vector-ref charges (cell-b code))
     (vector-ref charges (cell-c code))
     (vector-ref charges (cell-d code))))
(define (mass-code code)
  (+ (vector-ref occupancy (cell-a code))
     (vector-ref occupancy (cell-b code))
     (vector-ref occupancy (cell-c code))
     (vector-ref occupancy (cell-d code))))

(define (audit-rule)
  (let ((seen (make-vector 256 0)))
    (do ((i 0 (+ i 1)))
        ((>= i 256) #t)
      (let ((out (vector-ref rule i)))
        (if (or (< out 0) (>= out 256))
            (begin (display "AUDIT_FAIL_RANGE ") (display i) (newline) (raise "AUDIT_FAIL_RANGE"))
            #t)
        (if (= (vector-ref seen out) 1)
            (begin (display "AUDIT_FAIL_DUP ") (display out) (newline) (raise "AUDIT_FAIL_DUP"))
            (vector-set! seen out 1))
        (if (not (= (charge-code i) (charge-code out)))
            (begin (display "AUDIT_FAIL_Q ") (display i) (newline) (raise "AUDIT_FAIL_Q"))
            #t)))))

(define (step-state state phase)
  (let ((out (make-vector (* width height) 0))
        (offset (modulo phase 2)))
    (do ((by 0 (+ by 2)))
        ((>= by height) out)
      (do ((bx 0 (+ bx 2)))
          ((>= bx width) #t)
        (let* ((y0 (modulo (+ by offset) height))
               (x0 (modulo (+ bx offset) width))
               (y1 (modulo (+ y0 1) height))
               (x1 (modulo (+ x0 1) width))
               (code (encode (vector-ref state (index y0 x0))
                             (vector-ref state (index y0 x1))
                             (vector-ref state (index y1 x0))
                             (vector-ref state (index y1 x1))))
               (next (vector-ref rule code)))
          (vector-set! out (index y0 x0) (cell-a next))
          (vector-set! out (index y0 x1) (cell-b next))
          (vector-set! out (index y1 x0) (cell-c next))
          (vector-set! out (index y1 x1) (cell-d next)))))))

(define (run state phase)
  (if (>= phase steps)
      state
      (run (step-state state phase) (+ phase 1))))

(define (total-q state)
  (let ((q 0))
    (do ((i 0 (+ i 1)))
        ((>= i (* width height)) q)
      (set! q (+ q (vector-ref charges (vector-ref state i)))))))

(define (total-m state)
  (let ((m 0))
    (do ((i 0 (+ i 1)))
        ((>= i (* width height)) m)
      (set! m (+ m (vector-ref occupancy (vector-ref state i)))))))

(audit-rule)
(define final (run initial 0))
(display "AUDIT_OK") (newline)
(display "Q ") (display (total-q final)) (newline)
(display "M ") (display (total-m final)) (newline)
(display "FINAL")
(do ((i 0 (+ i 1)))
    ((>= i (* width height)) #t)
  (display " ") (display (vector-ref final i)))
(newline)
'''


def export_parity_case(
    rule: ReversibleRule,
    output: str | Path,
    *,
    size: int = 16,
    density: float = 0.28,
    seed: int = 303,
    steps: int = 256,
) -> dict[str, Any]:
    target = Path(output)
    target.parent.mkdir(parents=True, exist_ok=True)
    initial = make_state(
        size,
        size,
        inventory_for_density(size, size, density),
        seed=seed,
        arrangement="homogeneous",
    )
    state = initial.clone()
    for phase in range(steps):
        state = step_rule(state, rule, phase)
    source = generate_eshkol_parity_source(rule, initial, steps=steps)
    atomic_write_text(target, source)
    expected = {
        "schema": "zws-eshkol-parity-expected-v1",
        "rule_sha256": rule.sha256(),
        "size": size,
        "density": density,
        "seed": seed,
        "steps": steps,
        "initial_sha256": state_sha256(initial),
        "final_sha256": state_sha256(state),
        "final": [int(x) for x in state.reshape(-1).tolist()],
    }
    atomic_write_json(target.with_suffix(".expected.json"), expected)
    return expected


def run_eshkol_parity(
    source: str | Path,
    *,
    eshkol_run: str = "eshkol-run",
    timeout: int = 120,
) -> dict[str, Any]:
    source_path = Path(source)
    expected_path = source_path.with_suffix(".expected.json")
    expected = json.loads(expected_path.read_text(encoding="utf-8"))
    command = [eshkol_run, "--run", str(source_path)]
    result = subprocess.run(
        command,
        capture_output=True,
        text=True,
        timeout=timeout,
        check=False,
    )
    if result.returncode != 0:
        failure = {
            "schema": "zws-eshkol-parity-failure-v1",
            "source": str(source_path),
            "eshkol_run": eshkol_run,
            "command": command,
            "returncode": result.returncode,
            "passed": False,
            "stdout": result.stdout,
            "stderr": result.stderr,
        }
        atomic_write_json(source_path.with_suffix(".parity-failure.json"), failure)
        raise RuntimeError(
            f"Eshkol parity process exited {result.returncode}:\n{result.stdout}\n{result.stderr}"
        )
    lines = result.stdout.splitlines()
    if "AUDIT_OK" not in lines:
        raise RuntimeError(f"Eshkol did not report AUDIT_OK:\n{result.stdout}")
    final_line = next((line for line in lines if line.startswith("FINAL ")), None)
    if final_line is None:
        raise RuntimeError("Eshkol output did not contain FINAL lattice")
    actual = [int(x) for x in final_line.split()[1:]]
    expected_final = [int(x) for x in expected["final"]]
    mismatch = sum(a != b for a, b in zip(actual, expected_final, strict=False))
    if len(actual) != len(expected_final):
        mismatch += abs(len(actual) - len(expected_final))
    payload = {
        "schema": "zws-eshkol-parity-result-v1",
        "source": str(source_path),
        "command": command,
        "returncode": result.returncode,
        "mismatch_count": mismatch,
        "cell_count": len(expected_final),
        "expected_final_sha256": expected["final_sha256"],
        "actual_final_sha256": state_sha256(
            torch.tensor(actual, dtype=torch.uint8).reshape(expected["size"], expected["size"])
        )
        if len(actual) == len(expected_final)
        else None,
        "passed": mismatch == 0,
        "stdout": result.stdout,
        "stderr": result.stderr,
    }
    atomic_write_json(source_path.with_suffix(".parity.json"), payload)
    if mismatch:
        raise RuntimeError(f"Eshkol/Python parity failed with {mismatch} mismatched cells")
    failure_path = source_path.with_suffix(".parity-failure.json")
    failure_path.unlink(missing_ok=True)
    failure_path.with_suffix(failure_path.suffix + ".sha256").unlink(missing_ok=True)
    return payload
