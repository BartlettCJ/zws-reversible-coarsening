"""Derive the paper's \\hyphenation list from its own sources (the PROM1 method, 21 September 2026).

A name is a word that is capitalised somewhere in mid-sentence and never appears in lower case; an ordinary word that
happened to start a sentence appears in lower case elsewhere, or only ever at a sentence start. Names must never be
broken across a line, so every such word of eight letters or more is emitted with no permitted break point. Eight is
the threshold because with \\lefthyphenmin and \\righthyphenmin both at 4 a shorter word cannot break anyway.
Hyphenated names (Montalva-Medel) are NOT listed: TeX would read the hyphen as the permitted break; \\exhyphenpenalty
protects those instead. Citation keys, bibliography entry keys, code, labels and file names never typeset as words and
are stripped before scanning.

  python scripts/derive_hyphenation.py            writes paper/hyphenation.tex and prints the list
"""
from __future__ import annotations
import re
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1] / "paper"
SOURCES = ["main.tex", "supplement.tex", "references.bib"]

# Proper nouns from the bibliography's own fields: a journal, publisher, address or book title is a name whatever else
# the paper does with the word, and "Phys-ical Review" is as poor a break as "Pri-gogine". Taken before the stripping
# below, because the stripping removes entry keys and braces along with everything else. Title fields are included
# too: their title-case words are set solid in the reference list, and protecting an ordinary one from breaking costs
# nothing there, whereas "Inter-faces" or "Phys-ical Review" is the kind of break a reader stops at.
bib = (PAPER / "references.bib").read_text(encoding="utf-8")
bib_names = set()
for field in ("journal", "publisher", "address", "booktitle", "title", "series", "school", "institution"):
    for m in re.finditer(field + r"\s*=\s*\{([^{}]*)\}", bib, re.I):
        bib_names.update(w for w in re.findall(r"[A-Z][a-z]{7,}", m.group(1)))

text = ""
for name in SOURCES:
    s = (PAPER / name).read_text(encoding="utf-8")
    s = re.sub(r"(?m)^%.*$", "", s)                                                   # comments
    s = re.sub(r"\\cite[a-z]*(\[[^\]]*\])*\{[^}]*\}", " ", s)                          # citation keys never typeset
    s = re.sub(r"(?m)^@\w+\{[^,]*,", " ", s)                                           # bibliography entry keys
    s = re.sub(r"\\(code|path|texttt|label|ref|includegraphics|href|url)\*?(\[[^\]]*\])?\{[^}]*\}", " ", s)   # code, labels, files
    s = re.sub(r"\\[A-Za-z@]+\*?", " ", s)                                             # remaining control words; their arguments stay
    s = re.sub(r"\$[^$]*\$", " ", s)                                                   # inline maths
    text += "\n" + s

# every word with the two characters before it, so a capital at a sentence, brace or line start can be told apart
occ = [(m.group(0), text[max(0, m.start() - 5):m.start()]) for m in re.finditer(r"[A-Za-z][A-Za-z']*[A-Za-z]", text)]
words = [w for w, _ in occ]
lower_forms = {w.lower() for w in words if w[0].islower()}
START = re.compile(r"[.!?:\n{]\s?$|^\s*$")
INITIAL = re.compile(r"(^|[\s{])[A-Z]\.\s?$")          # "Y. " before a surname is an initial, not a sentence end
mid = {w for w, pre in occ if w[0].isupper() and w[1:].islower() and (not START.search(pre) or INITIAL.search(pre))}
names = sorted(bib_names | {w for w in mid if w.lower() not in lower_forms and len(w) >= 8 and "'" not in w})

# mixed-case identifiers typeset as words (PyTorch-style); all-capital tokens are left alone
extra = sorted({w for w in words if len(w) >= 8 and w.isalpha() and any(c.islower() for c in w[1:])
                and sum(c.isupper() for c in w[1:]) >= 1 and w not in names})

lines = [
    "% Generated by scripts/derive_hyphenation.py from main.tex, supplement.tex and references.bib.",
    "% A word capitalised in mid-sentence and never seen in lower case is a name and is never broken across a line;",
    "% mixed-case identifiers are protected the same way. Regenerate after any edit that adds a name.",
    "\\lefthyphenmin=4 \\righthyphenmin=4",
    "\\exhyphenpenalty=10000",
    "\\hyphenation{%",
]
for w in names + extra:
    lines.append("  " + w)
lines.append("}")
out = PAPER / "hyphenation.tex"
out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print("names (capitalised in mid-sentence, never lower case):", len(names)); print("  ", " ".join(names))
print("mixed-case identifiers:", len(extra)); print("  ", " ".join(extra))
print("written:", out)
